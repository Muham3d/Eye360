#!/bin/bash

################################################################################
# PatrolManager Database Setup Script
#
# This script initializes the PostgreSQL database for development.
# It starts Docker containers, runs migrations, and seeds initial data.
#
# Usage:
#   ./scripts/db/setup.sh [options]
#
# Options:
#   -f, --force    Re-create database from scratch (WARNING: deletes all data)
#   -s, --skip-seed Skip running seeders
#   -h, --help     Show this help message
################################################################################

set -e  # Exit on error
set -u  # Exit on undefined variable

# Script directory
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

# Color output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Default options
FORCE_RECREATE=false
SKIP_SEED=false

# Parse command line arguments
while [[ $# -gt 0 ]]; do
  case $1 in
    -f|--force)
      FORCE_RECREATE=true
      shift
      ;;
    -s|--skip-seed)
      SKIP_SEED=true
      shift
      ;;
    -h|--help)
      echo "Usage: $0 [options]"
      echo ""
      echo "Options:"
      echo "  -f, --force     Re-create database from scratch (WARNING: deletes all data)"
      echo "  -s, --skip-seed Skip running seeders"
      echo "  -h, --help      Show this help message"
      exit 0
      ;;
    *)
      echo -e "${RED}Unknown option: $1${NC}"
      echo "Use -h or --help for usage information"
      exit 1
      ;;
  esac
done

# Print header
echo -e "${BLUE}================================================${NC}"
echo -e "${BLUE}  PatrolManager Database Setup${NC}"
echo -e "${BLUE}================================================${NC}"
echo ""

# Change to project root
cd "$PROJECT_ROOT"

# Check if Docker is installed
if ! command -v docker &> /dev/null; then
    echo -e "${RED}Error: Docker is not installed${NC}"
    echo "Please install Docker Desktop before running this script"
    exit 1
fi

# Check if Docker Compose is available
if ! docker compose version &> /dev/null && ! docker-compose version &> /dev/null; then
    echo -e "${RED}Error: Docker Compose is not available${NC}"
    echo "Please ensure Docker Compose is installed"
    exit 1
fi

# Determine docker compose command
DOCKER_COMPOSE="docker compose"
if ! docker compose version &> /dev/null; then
    DOCKER_COMPOSE="docker-compose"
fi

# Step 1: Check if .env file exists
echo -e "${BLUE}[1/6] Checking environment configuration...${NC}"
if [ ! -f "$PROJECT_ROOT/.env" ]; then
    echo -e "${YELLOW}Warning: .env file not found${NC}"
    echo "Creating .env file with default values..."

    cat > "$PROJECT_ROOT/.env" << EOF
# PatrolManager Environment Configuration
# Generated by database setup script on $(date)

# Node Environment
NODE_ENV=development

# Server Configuration
PORT=3000
SERVER_HOST=0.0.0.0
API_URL=http://localhost:3000

# Database Configuration
DB_HOST=localhost
DB_PORT=5432
DB_NAME=patrolmanager
DB_USER=patrolmanager
DB_PASSWORD=patrolmanager_dev_password
DB_SSL=false
DB_POOL_MAX=20
DB_POOL_MIN=2
DB_POOL_ACQUIRE=10000
DB_POOL_IDLE=10000

# JWT Configuration
JWT_SECRET=change_this_jwt_secret_in_production_$(openssl rand -hex 32)
JWT_EXPIRES_IN=1h
JWT_REFRESH_EXPIRES_IN=7d
JWT_ISSUER=patrolmanager
JWT_AUDIENCE=patrolmanager-api

# Session Configuration
SESSION_SECRET=change_this_session_secret_in_production_$(openssl rand -hex 32)
SESSION_COOKIE_MAX_AGE=86400000

# CORS Configuration
CORS_ORIGIN=http://localhost:3000,http://localhost:5173

# Rate Limiting
RATE_LIMIT_WINDOW_MS=900000
RATE_LIMIT_MAX=1000

# Logging
LOG_LEVEL=debug
LOG_FORMAT=json
LOG_FILE_PATH=./logs

# PgAdmin Configuration (Optional)
PGADMIN_EMAIL=admin@patrolmanager.local
PGADMIN_PASSWORD=pgadmin_password
PGADMIN_PORT=5050

# Redis Configuration (Optional)
REDIS_PORT=6379
EOF
    echo -e "${GREEN}.env file created${NC}"
else
    echo -e "${GREEN}.env file found${NC}"
fi

# Step 2: Stop existing containers if force recreate
if [ "$FORCE_RECREATE" = true ]; then
    echo -e "${BLUE}[2/6] Stopping existing containers...${NC}"
    $DOCKER_COMPOSE --file docker-compose.yml --profile admin down -v
    echo -e "${GREEN}Containers stopped${NC}"
else
    echo -e "${BLUE}[2/6] Checking container status...${NC}"
fi

# Step 3: Start PostgreSQL container
echo -e "${BLUE}[3/6] Starting PostgreSQL container...${NC}"
$DOCKER_COMPOSE --file docker-compose.yml up -d postgres

# Wait for PostgreSQL to be healthy
echo "Waiting for PostgreSQL to be ready..."
MAX_RETRIES=30
RETRY_COUNT=0

while [ $RETRY_COUNT -lt $MAX_RETRIES ]; do
    if docker exec patrolmanager-postgres pg_isready -U patrolmanager -d patrolmanager &> /dev/null; then
        echo -e "${GREEN}PostgreSQL is ready${NC}"
        break
    fi
    RETRY_COUNT=$((RETRY_COUNT + 1))
    echo "Waiting... ($RETRY_COUNT/$MAX_RETRIES)"
    sleep 2
done

if [ $RETRY_COUNT -eq $MAX_RETRIES ]; then
    echo -e "${RED}Error: PostgreSQL failed to start${NC}"
    exit 1
fi

# Step 4: Install dependencies if needed
echo -e "${BLUE}[4/6] Checking backend dependencies...${NC}"
if [ ! -d "$PROJECT_ROOT/backend/node_modules" ]; then
    echo "Installing backend dependencies..."
    cd "$PROJECT_ROOT/backend"
    npm install
    cd "$PROJECT_ROOT"
    echo -e "${GREEN}Dependencies installed${NC}"
else
    echo -e "${GREEN}Dependencies already installed${NC}"
fi

# Step 5: Run database migrations
echo -e "${BLUE}[5/6] Running database migrations...${NC}"
cd "$PROJECT_ROOT/backend"

# Use Node and run Sequelize CLI
if [ "$FORCE_RECREATE" = true ]; then
    echo "Resetting database (dropping all tables)..."
    npx sequelize-cli db:drop 2>/dev/null || true
    npx sequelize-cli db:create
fi

npx sequelize-cli db:migrate
echo -e "${GREEN}Migrations completed${NC}"

# Step 6: Run seeders
if [ "$SKIP_SEED" = false ]; then
    echo -e "${BLUE}[6/6] Running database seeders...${NC}"
    npx sequelize-cli db:seed:all
    echo -e "${GREEN}Seeders completed${NC}"
else
    echo -e "${YELLOW}[6/6] Skipping seeders${NC}"
fi

# Final summary
echo ""
echo -e "${GREEN}================================================${NC}"
echo -e "${GREEN}  Database Setup Complete!${NC}"
echo -e "${GREEN}================================================${NC}"
echo ""
echo "Database connection details:"
echo "  Host: localhost"
echo "  Port: 5432"
echo "  Database: patrolmanager"
echo "  User: patrolmanager"
echo ""
echo "Development users (password: TestPassword123!):"
echo "  - admin@patrolmanager.local (Admin)"
echo "  - manager@patrolmanager.local (Manager)"
echo "  - supervisor@patrolmanager.local (Supervisor)"
echo "  - guard@patrolmanager.local (Guard)"
echo ""
echo "To start the backend server:"
echo "  cd backend && npm run dev"
echo ""
echo "To access PgAdmin (if enabled):"
echo "  URL: http://localhost:5050"
echo "  Email: admin@patrolmanager.local"
echo "  Password: pgadmin_password"
echo ""
echo -e "${YELLOW}Note: Don't forget to update the JWT_SECRET and SESSION_SECRET in .env for production!${NC}"
