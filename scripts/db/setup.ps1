################################################################################
# PatrolManager Database Setup Script (PowerShell)
#
# This script initializes the PostgreSQL database for development.
# It starts Docker containers, runs migrations, and seeds initial data.
#
# Usage:
#   .\scripts\db\setup.ps1 [options]
#
# Options:
#   -Force         Re-create database from scratch (WARNING: deletes all data)
#   -SkipSeed      Skip running seeders
#   -Help          Show this help message
################################################################################

[CmdletBinding()]
param(
    [switch]$Force,
    [switch]$SkipSeed,
    [switch]$Help
)

# Show help
if ($Help) {
    Write-Host "Usage: .\scripts\db\setup.ps1 [options]" -ForegroundColor Cyan
    Write-Host ""
    Write-Host "Options:"
    Write-Host "  -Force         Re-create database from scratch (WARNING: deletes all data)"
    Write-Host "  -SkipSeed      Skip running seeders"
    Write-Host "  -Help          Show this help message"
    exit 0
}

# Script directory
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$ProjectRoot = Split-Path -Parent (Split-Path -Parent $ScriptDir)

# Change to project root
Set-Location $ProjectRoot

# Print header
Write-Host "================================================" -ForegroundColor Cyan
Write-Host "  PatrolManager Database Setup" -ForegroundColor Cyan
Write-Host "================================================" -ForegroundColor Cyan
Write-Host ""

# Step 1: Check if Docker is installed
Write-Host "[1/6] Checking Docker installation..." -ForegroundColor Cyan
try {
    $dockerVersion = docker --version 2>&1
    if ($LASTEXITCODE -ne 0) {
        throw "Docker not found"
    }
    Write-Host "Docker found: $dockerVersion" -ForegroundColor Green
} catch {
    Write-Host "Error: Docker is not installed or not running" -ForegroundColor Red
    Write-Host "Please install Docker Desktop before running this script"
    exit 1
}

# Step 2: Check .env file
Write-Host "[2/6] Checking environment configuration..." -ForegroundColor Cyan
$EnvFile = Join-Path $ProjectRoot ".env"
if (-not (Test-Path $EnvFile)) {
    Write-Host "Warning: .env file not found" -ForegroundColor Yellow
    Write-Host "Creating .env file with default values..."

    # Generate random secrets
    $jwtSecret = -join ((48..57) + (65..90) + (97..122) | Get-Random -Count 32 | ForEach-Object { [char]$_ })
    $sessionSecret = -join ((48..57) + (65..90) + (97..122) | Get-Random -Count 32 | ForEach-Object { [char]$_ })

    @"
# PatrolManager Environment Configuration
# Generated by database setup script on $(Get-Date -Format "o")

# Node Environment
NODE_ENV=development

# Server Configuration
PORT=3000
SERVER_HOST=0.0.0.0
API_URL=http://localhost:3000

# Database Configuration
DB_HOST=localhost
DB_PORT=5432
DB_NAME=patrolmanager
DB_USER=patrolmanager
DB_PASSWORD=patrolmanager_dev_password
DB_SSL=false
DB_POOL_MAX=20
DB_POOL_MIN=2
DB_POOL_ACQUIRE=10000
DB_POOL_IDLE=10000

# JWT Configuration
JWT_SECRET=change_this_jwt_secret_in_production_$jwtSecret
JWT_EXPIRES_IN=1h
JWT_REFRESH_EXPIRES_IN=7d
JWT_ISSUER=patrolmanager
JWT_AUDIENCE=patrolmanager-api

# Session Configuration
SESSION_SECRET=change_this_session_secret_in_production_$sessionSecret
SESSION_COOKIE_MAX_AGE=86400000

# CORS Configuration
CORS_ORIGIN=http://localhost:3000,http://localhost:5173

# Rate Limiting
RATE_LIMIT_WINDOW_MS=900000
RATE_LIMIT_MAX=1000

# Logging
LOG_LEVEL=debug
LOG_FORMAT=json
LOG_FILE_PATH=./logs

# PgAdmin Configuration (Optional)
PGADMIN_EMAIL=admin@patrolmanager.local
PGADMIN_PASSWORD=pgadmin_password
PGADMIN_PORT=5050

# Redis Configuration (Optional)
REDIS_PORT=6379
"@ | Out-File -FilePath $EnvFile -Encoding UTF8

    Write-Host ".env file created" -ForegroundColor Green
} else {
    Write-Host ".env file found" -ForegroundColor Green
}

# Step 3: Stop existing containers if force recreate
if ($Force) {
    Write-Host "[3/6] Stopping existing containers..." -ForegroundColor Cyan
    docker compose --file docker-compose.yml --profile admin down -v 2>$null
    if ($LASTEXITCODE -eq 0) {
        Write-Host "Containers stopped" -ForegroundColor Green
    }
} else {
    Write-Host "[3/6] Checking container status..." -ForegroundColor Cyan
}

# Step 4: Start PostgreSQL container
Write-Host "[4/6] Starting PostgreSQL container..." -ForegroundColor Cyan
docker compose --file docker-compose.yml up -d postgres

if ($LASTEXITCODE -ne 0) {
    Write-Host "Error: Failed to start PostgreSQL container" -ForegroundColor Red
    exit 1
}

# Wait for PostgreSQL to be healthy
Write-Host "Waiting for PostgreSQL to be ready..."
$MaxRetries = 30
$RetryCount = 0
$Ready = $false

while ($RetryCount -lt $MaxRetries) {
    $result = docker exec patrolmanager-postgres pg_isready -U patrolmanager -d patrolmanager 2>&1
    if ($LASTEXITCODE -eq 0) {
        $Ready = $true
        Write-Host "PostgreSQL is ready" -ForegroundColor Green
        break
    }
    $RetryCount++
    Write-Host "Waiting... ($RetryCount/$MaxRetries)"
    Start-Sleep -Seconds 2
}

if (-not $Ready) {
    Write-Host "Error: PostgreSQL failed to start" -ForegroundColor Red
    exit 1
}

# Step 5: Install dependencies if needed
Write-Host "[5/6] Checking backend dependencies..." -ForegroundColor Cyan
$NodeModulesPath = Join-Path $ProjectRoot "backend\node_modules"
if (-not (Test-Path $NodeModulesPath)) {
    Write-Host "Installing backend dependencies..."
    Set-Location (Join-Path $ProjectRoot "backend")
    npm install
    Set-Location $ProjectRoot
    Write-Host "Dependencies installed" -ForegroundColor Green
} else {
    Write-Host "Dependencies already installed" -ForegroundColor Green
}

# Step 6: Run database migrations
Write-Host "[6/6] Running database migrations..." -ForegroundColor Cyan
Set-Location (Join-Path $ProjectRoot "backend")

if ($Force) {
    Write-Host "Resetting database (dropping all tables)..."
    npx sequelize-cli db:drop 2>$null
    npx sequelize-cli db:create
}

npx sequelize-cli db:migrate
if ($LASTEXITCODE -ne 0) {
    Write-Host "Error: Migrations failed" -ForegroundColor Red
    Set-Location $ProjectRoot
    exit 1
}
Write-Host "Migrations completed" -ForegroundColor Green

# Step 7: Run seeders
if (-not $SkipSeed) {
    Write-Host "[7/7] Running database seeders..." -ForegroundColor Cyan
    npx sequelize-cli db:seed:all
    if ($LASTEXITCODE -ne 0) {
        Write-Host "Warning: Some seeders may have failed" -ForegroundColor Yellow
    } else {
        Write-Host "Seeders completed" -ForegroundColor Green
    }
} else {
    Write-Host "[7/7] Skipping seeders" -ForegroundColor Yellow
}

Set-Location $ProjectRoot

# Final summary
Write-Host ""
Write-Host "================================================" -ForegroundColor Green
Write-Host "  Database Setup Complete!" -ForegroundColor Green
Write-Host "================================================" -ForegroundColor Green
Write-Host ""
Write-Host "Database connection details:"
Write-Host "  Host: localhost"
Write-Host "  Port: 5432"
Write-Host "  Database: patrolmanager"
Write-Host "  User: patrolmanager"
Write-Host ""
Write-Host "Development users (password: TestPassword123!):"
Write-Host "  - admin@patrolmanager.local (Admin)"
Write-Host "  - manager@patrolmanager.local (Manager)"
Write-Host "  - supervisor@patrolmanager.local (Supervisor)"
Write-Host "  - guard@patrolmanager.local (Guard)"
Write-Host ""
Write-Host "To start the backend server:"
Write-Host "  cd backend && npm run dev"
Write-Host ""
Write-Host "To access PgAdmin (if enabled):"
Write-Host "  URL: http://localhost:5050"
Write-Host "  Email: admin@patrolmanager.local"
Write-Host "  Password: pgadmin_password"
Write-Host ""
Write-Host "Note: Don't forget to update the JWT_SECRET and SESSION_SECRET in .env for production!" -ForegroundColor Yellow
